r"""Generate tonality's logo artwork from Playfair Display Italic.

The mark is a lowercase italic `t`; the wordmark is "tonality" in the same face. Both are
turned into plain SVG paths, so no font ships with the app. Playfair Display is under the
SIL Open Font License 1.1, which allows this.

Outputs (committed; rerun only to change the artwork):
  ui/lib/design/brand.ts      path data for the in-app mark and wordmark
  src-tauri/icons/icon.svg    the app icon source (then regenerate the icons, below)

Usage:
  python -m venv /tmp/brand && /tmp/brand/bin/pip install fonttools uharfbuzz
  curl -L -o /tmp/PlayfairDisplay-Italic.ttf \
    'https://raw.githubusercontent.com/google/fonts/main/ofl/playfairdisplay/PlayfairDisplay-Italic%5Bwght%5D.ttf'
  /tmp/brand/bin/python scripts/brand.py /tmp/PlayfairDisplay-Italic.ttf
  npx tauri icon src-tauri/icons/icon.svg -o /tmp/icons && cp /tmp/icons/{32x32,64x64,128x128,128x128@2x}.png \
    /tmp/icons/icon.{png,icns,ico} src-tauri/icons/
"""

import io
import sys
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
WEIGHT = 600  # the mark and wordmark
ICON_WEIGHT = 600  # same as the mark; heavier weights lengthen the crossbar and lose the hook
TRACKING = 30  # em units (of 1000); the wordmark is mostly shown small, where Playfair is tight
ICON_BG = "#17171a"
ICON_FG = "#f2efe8"


def instance(path: str, wght: int):
    font = instancer.instantiateVariableFont(TTFont(path), {"wght": wght})
    buf = io.BytesIO()
    font.save(buf)
    return font, buf.getvalue()


def shape(font, data: bytes, text: str, tracking: int = 0):
    """Glyph names and pen positions for `text`, kerned, plus `tracking` em units per letter."""
    hbfont = hb.Font(hb.Face(data))
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(hbfont, buf, {"kern": True, "liga": False})
    order = font.getGlyphOrder()
    x, out = 0, []
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        out.append((order[info.codepoint], x + pos.x_offset, pos.y_offset))
        x += pos.x_advance + tracking
    return out


def outline(font, glyphs, pad: float):
    """One path for the glyphs, y flipped to SVG, cropped to the ink plus `pad` (em units)."""
    gs = font.getGlyphSet()
    bounds = BoundsPen(gs)
    for name, x, y in glyphs:
        gs[name].draw(TransformPen(bounds, (1, 0, 0, 1, x, y)))
    x0, y0, x1, y1 = bounds.bounds
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    for name, x, y in glyphs:
        # font units are y-up; SVG is y-down. Place the ink's top-left at (pad, pad).
        gs[name].draw(TransformPen(pen, (1, 0, 0, -1, x - x0 + pad, y1 + y + pad)))
    w, h = x1 - x0 + 2 * pad, y1 - y0 + 2 * pad
    return pen.getCommands(), round(w, 1), round(h, 1)


def main(path: str):
    font, data = instance(path, WEIGHT)
    mark, mw, mh = outline(font, shape(font, data, "t"), 0)
    word, ww, wh = outline(font, shape(font, data, "tonality", TRACKING), 0)

    (ROOT / "ui/lib/design/brand.ts").write_text(
        "// Generated by scripts/brand.py from Playfair Display Italic (SIL OFL 1.1). Don't edit.\n\n"
        "/** The mark: a lowercase italic t. */\n"
        f'export const MARK = {{ width: {mw}, height: {mh}, d: "{mark}" }};\n\n'
        '/** The wordmark: "tonality". */\n'
        f'export const WORDMARK = {{ width: {ww}, height: {wh}, d: "{word}" }};\n'
    )

    ifont, idata = instance(path, ICON_WEIGHT)
    t, tw, th = outline(ifont, shape(ifont, idata, "t"), 0)
    # 1024 canvas, rounded square inset a little, glyph about 68% of the square's height,
    # centred on its ink (the tail and crossbar balance optically there).
    size, inset, radius = 1024, 48, 224
    box = size - 2 * inset
    s = 0.68 * box / th
    tx, ty = (size - tw * s) / 2, (size - th * s) / 2
    (ROOT / "src-tauri/icons/icon.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">\n'
        f'  <!-- Generated by scripts/brand.py (Playfair Display Italic, SIL OFL 1.1). -->\n'
        f'  <rect x="{inset}" y="{inset}" width="{box}" height="{box}" rx="{radius}" fill="{ICON_BG}"/>\n'
        f'  <path transform="translate({tx:.1f} {ty:.1f}) scale({s:.4f})" fill="{ICON_FG}" d="{t}"/>\n'
        "</svg>\n"
    )
    print("wrote ui/lib/design/brand.ts and src-tauri/icons/icon.svg")


if __name__ == "__main__":
    main(sys.argv[1])
